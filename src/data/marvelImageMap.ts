/**
 * Universal resolver to obtain authentic `Images Marvel` artwork URL.
 * Accepts either:
 * - Character object ({ id, name, imageUrl })
 * - Character ID string (e.g. 'char-m-001')
 * - Character Name string (e.g. 'Iron Man (Mark 85)' or 'Spider-Man')
 */
export function getCharacterImageUrl(
  characterOrId?: string | { id?: string; name?: string; imageUrl?: string } | null
): string {
  const filenameUrl = (id?: string): string => {
    const filename = id ? MARVEL_CHARACTER_FILENAMES[id] : undefined;
    return filename ? `/Images%20Marvel/${encodeURIComponent(filename).replace(/%27/g, "'")}` : '';
  };
  if (!characterOrId) return '';

  // If object was passed
  if (typeof characterOrId === 'object') {
    if (characterOrId.id && MARVEL_CHARACTER_FILENAMES[characterOrId.id]) {
      return filenameUrl(characterOrId.id);
    }
    if (characterOrId.name && MARVEL_NAME_TO_IMAGE[characterOrId.name]) {
      return MARVEL_NAME_TO_IMAGE[characterOrId.name];
    }
    if (characterOrId.name) {
      const normalized = characterOrId.name.toLowerCase().replace(/[^a-z0-9]/g, '');
      const key = Object.keys(MARVEL_NAME_TO_IMAGE).find(
        k => k.toLowerCase().replace(/[^a-z0-9]/g, '') === normalized
      );
      if (key) return MARVEL_NAME_TO_IMAGE[key];
    }
    if (characterOrId.imageUrl && characterOrId.imageUrl.includes('/Images')) {
      return characterOrId.imageUrl;
    }
    return '';
  }

  // If string was passed (could be ID or Name)
  if (MARVEL_CHARACTER_FILENAMES[characterOrId]) {
    return filenameUrl(characterOrId);
  }

  if (MARVEL_NAME_TO_IMAGE[characterOrId]) {
    return MARVEL_NAME_TO_IMAGE[characterOrId];
  }

  const normalized = characterOrId.toLowerCase().replace(/[^a-z0-9]/g, '');
  const key = Object.keys(MARVEL_NAME_TO_IMAGE).find(
    k => k.toLowerCase().replace(/[^a-z0-9]/g, '') === normalized
  );
  if (key) {
    return MARVEL_NAME_TO_IMAGE[key];
  }

  return '';
}
